#!/usr/bin/env node
/**
 * Generate docs/adr/README.md from the ADR front-matter.
 *
 * The index is committed so it renders on the repository host, and diff-gated so it
 * can never drift from the ADRs it indexes. Regenerate; never hand-edit.
 *
 *   node scripts/gen-adr-index.mjs           write the index
 *   node scripts/gen-adr-index.mjs --check   fail if the committed index is stale
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const ADR_DIR = join(REPO, "docs", "adr");
const OUT = join(ADR_DIR, "README.md");
const VALID_STATUS = /^(proposed|accepted|rejected|deprecated|superseded by ADR-\d{4})$/;

function frontMatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$/);
    if (kv) out[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, "");
  }
  return out;
}

const problems = [];
const records = [];
const seen = new Map();

for (const file of readdirSync(ADR_DIR).sort()) {
  if (!file.endsWith(".md") || file === "README.md" || file === "template.md") continue;
  const fm = frontMatter(readFileSync(join(ADR_DIR, file), "utf8"));
  if (!fm) { problems.push(`${file}: no front-matter`); continue; }
  for (const req of ["title", "status", "date", "adr"]) {
    if (!fm[req]) problems.push(`${file}: front-matter missing '${req}'`);
  }
  if (fm.status && !VALID_STATUS.test(fm.status)) {
    problems.push(`${file}: invalid status '${fm.status}'`);
  }
  const num = String(fm.adr ?? "").padStart(4, "0");
  if (!/^\d{4}$/.test(num)) problems.push(`${file}: 'adr' is not a 4-digit number`);
  if (seen.has(num)) problems.push(`${file}: ADR number ${num} already used by ${seen.get(num)}`);
  seen.set(num, file);
  if (!file.startsWith(num + "-")) problems.push(`${file}: filename does not start with its ADR number ${num}`);
  records.push({ num, file, title: fm.title, status: fm.status, date: fm.date, superseded_by: fm.superseded_by });
}

// A superseding reference must point at an ADR that exists.
for (const r of records) {
  const m = (r.status || "").match(/superseded by ADR-(\d{4})/);
  if (m && !seen.has(m[1])) problems.push(`${r.file}: superseded by ADR-${m[1]}, which does not exist`);
}

if (problems.length) {
  console.error("adr-index: FAILED\n");
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

records.sort((a, b) => a.num.localeCompare(b.num));

const body = `<!-- GENERATED by scripts/gen-adr-index.mjs — do not edit. -->
# Architecture decision records

${records.length} decisions. Format is [MADR 4.0](https://adr.github.io/madr/) — see
[ADR-0000](0000-record-decisions-with-madr.md) and [\`template.md\`](template.md).

Numbers are never reused. Superseding an ADR edits both files: the old one gets
\`status: superseded by ADR-NNNN\` and keeps its content. Nothing is deleted.

| ADR | Decision | Status | Date |
| --- | --- | --- | --- |
${records.map((r) => `| [${r.num}](${r.file}) | ${r.title} | \`${r.status}\` | ${r.date} |`).join("\n")}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing counts as stale */ }
  if (current !== body) {
    console.error("adr-index: FAILED — docs/adr/README.md is stale. Run: node scripts/gen-adr-index.mjs");
    process.exit(1);
  }
  console.log(`adr-index: in sync (${records.length} ADRs).`);
} else {
  writeFileSync(OUT, body);
  console.log(`adr-index: wrote ${records.length} ADRs to docs/adr/README.md`);
}
